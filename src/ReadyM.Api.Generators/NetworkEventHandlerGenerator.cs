using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace ReadyM.Api.Generators;

/// <summary>
/// Runs on a mod project, client or server. Collects the <c>[EventHandler]</c> methods it declares and emits the
/// ladder that runs them: the policy check first, then the stages in order, stopping at the first refusal. The
/// server also sends an accepted event on to the audience its scope names, and a refusal back to the origin
/// alone. A client only ever sends to the server.
/// </summary>
[Generator]
internal class NetworkEventHandlerGenerator : IIncrementalGenerator
{
    private const string EventAttribute = "ReadyM.SDK.Attributes.NetworkEventAttribute";
    private const string HandlerAttribute = "EventHandlerAttribute";
    private const string Events = "global::ReadyM.SDK.Events";

    /// <summary>The server's own seams: ownership, scopes and the fan-out all live where that state is.</summary>
    private const string ServerEvents = "global::ReadyM.SDK.Server.Events";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var owners = context.SyntaxProvider
            .CreateSyntaxProvider(Predicate, Transform)
            .Where(o => o is not null)
            .Collect();

        context.RegisterSourceOutput(context.CompilationProvider.Combine(owners), Generate);
    }

    private static bool Predicate(SyntaxNode node, CancellationToken _)
        => node is ClassDeclarationSyntax { Members.Count: > 0 };

    private static INamedTypeSymbol? Transform(GeneratorSyntaxContext context, CancellationToken _)
    {
        if (context.SemanticModel.GetDeclaredSymbol(context.Node) is not INamedTypeSymbol symbol)
            return null;

        return symbol.GetMembers().OfType<IMethodSymbol>().Any(Marked) ? symbol : null;
    }

    private static bool Marked(IMethodSymbol method)
        => method.GetAttributes().Any(a => a.AttributeClass?.Name == HandlerAttribute);

    private static void Generate(
        SourceProductionContext context, (Compilation Compilation, ImmutableArray<INamedTypeSymbol?> Owners) input)
    {
        var owners = input.Owners.Where(o => o is not null).Select(o => o!).ToList();
        if (owners.Count == 0)
            return;

        var onServer = ServerRpcHandlerGenerator.IsServerSide(input.Compilation);
        var mod = input.Compilation.AssemblyName ?? "this mod";

        var handlers = owners
            .SelectMany(owner => owner.GetMembers().OfType<IMethodSymbol>().Where(Marked)
                .Select(method => Handler.Read(owner, method)))
            .Where(h => h is not null)
            .Select(h => h!)
            .ToList();

        foreach (var handler in handlers)
            Validate(context, handler, onServer);

        var byEvent = handlers
            .GroupBy(h => h.Event, SymbolEqualityComparer.Default)
            .OrderBy(g => g.Key!.Name, System.StringComparer.Ordinal)
            .ToList();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("using LiteNetLib.Utils;");
        sb.AppendLine();
        sb.AppendLine($"namespace {mod}.Generated;");
        sb.AppendLine();

        foreach (var group in byEvent)
            EmitDispatch(sb, (INamedTypeSymbol)group.Key!, [.. group], mod, onServer);

        context.AddSource("NetworkEventDispatch.g.cs", sb.ToString());
    }

    /// <summary>What a handler may not say. Each is a hard error rather than a handler that never fires.</summary>
    private static void Validate(SourceProductionContext context, Handler handler, bool onServer)
    {
        var location = handler.Method.Locations.FirstOrDefault();
        var name = $"{handler.Owner.Name}.{handler.Method.Name}";

        if (handler.ByRef && handler.Stage != Stage.Filter)
            Report(context, location, "NEVT010", "Only a filter may change an event",
                $"'{name}' takes the event by ref at Stage.{handler.Stage}. Only Stage.Filter may change it; the rest take it by in.");

        if (handler.Stage == Stage.Rejected)
        {
            if (handler.Reject is null)
                Report(context, location, "NEVT012", "Nothing to reject with",
                    $"'{name}' handles Stage.Rejected for '{handler.Event.Name}', whose declaration named no Reject type, so there is no reason to hand it.");
            else if (handler.Reason is null || !SymbolEqualityComparer.Default.Equals(handler.Reason, handler.Reject))
                Report(context, location, "NEVT011", "Wrong reject type",
                    $"'{name}' handles Stage.Rejected for '{handler.Event.Name}', which declared Reject = typeof({handler.Reject.Name}), so its reason parameter must be a {handler.Reject.Name}.");
        }

        if (handler.SkipOnRaiser && handler.Stage != Stage.Apply)
            Report(context, location, "NEVT013", "Nothing to skip",
                $"'{name}' sets SkipOnRaiser at Stage.{handler.Stage}. Only an Apply has an effect the raiser already had, so only an Apply can be skipped.");

        if (!onServer && handler.Stage is Stage.Validate or Stage.Filter)
            Report(context, location, "NEVT020", "Stage cannot run here",
                $"'{name}' handles Stage.{handler.Stage}, which always runs on the server, in a client project where it would never fire.");
    }

    private static void EmitDispatch(
        StringBuilder sb, INamedTypeSymbol declared, List<Handler> handlers, string mod, bool onServer)
    {
        var type = declared.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var declaration = declared.GetAttributes()
            .First(a => a.AttributeClass?.ToDisplayString() == EventAttribute);
        var scope = AttributeUtils.EnumArgument(declaration.ConstructorArguments[0], Scope.Server);

        // By name, so the emitted call reads like the declaration and survives a reorder of the real enum
        var policy = "global::ReadyM.SDK.Attributes.Policy."
                     + (AttributeUtils.EnumMemberName(declaration.ConstructorArguments[1]) ?? "ServerAuthoritative");
        var manifest = $"global::{declared.ContainingNamespace.ToDisplayString()}.NetworkEventManifest";
        var reject = declaration.NamedArguments
            .FirstOrDefault(n => n.Key == "Reject").Value.Value as INamedTypeSymbol;
        var subject = Member(declared, "SubjectAttribute");
        var target = Member(declared, "TargetAttribute");
        var owners = handlers.Select(h => h.Owner).Distinct(SymbolEqualityComparer.Default).ToList();

        sb.AppendLine($"/// <summary>Runs this mod's handlers for {declared.Name}, in stage order.</summary>");
        sb.AppendLine($"{Visibility(owners)} sealed class {declared.Name}Dispatch(");
        sb.AppendLine(string.Join(",\n", owners.Select(o =>
            $"    {o!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)} {Field(o)}")));
        var dispatchBase = onServer
            ? ServerEvents + ".ServerNetworkEventDispatchBase"
            : Events + ".NetworkEventDispatchBase";

        sb.AppendLine($") : {dispatchBase}, {Events}.INetworkEventDispatch<{type}>");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>This event's code on the wire, once the host has placed the mod's block.</summary>");
        sb.AppendLine("    protected override global::ReadyM.Api.Multiplayer.Protocol.Enums.RelayMessageCode Code()");
        sb.AppendLine($"        => {manifest}.{declared.Name}Code + {manifest}.Offset;");
        sb.AppendLine();

        var after = handlers.Where(h => h.After is not null).Select(h => $"\"{h.After}\"").Distinct().ToList();
        if (after.Count > 0)
        {
            sb.AppendLine("    /// <summary>Mods this one's handlers run behind, resolved once at startup.</summary>");
            sb.AppendLine($"    public static readonly string[] After = [{string.Join(", ", after)}];");
            sb.AppendLine();
        }

        sb.AppendLine($"    public void Dispatch("
                      + $"{type} e, global::ReadyM.Api.Idents.PlayerId origin, bool raisedHere, bool vouched)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var cancellation = new {Events}.EventCancellation();");
        sb.AppendLine($"        var ctx = new {Events}.EventContext(origin, raisedHere, cancellation);");
        sb.AppendLine();

        if (onServer)
        {
            var check = subject is null
                ? $"{ServerEvents}.ServerNetworkEventPolicy.Allows(this, {policy}, origin)"
                : $"{ServerEvents}.ServerNetworkEventPolicy.Allows(this, {policy}, e.{subject.Name}, origin)";

            sb.AppendLine($"        if (!vouched && !{check})");
            sb.AppendLine("        {");
            sb.AppendLine("            Refuse(in e, ctx, cancellation);");
            sb.AppendLine("            return;");
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        foreach (var stage in new[] { Stage.Validate, Stage.Filter, Stage.Apply, Stage.Observe })
        {
            foreach (var handler in handlers.Where(h => h.Stage == stage))
            {
                if (!onServer && stage is Stage.Validate or Stage.Filter)
                    continue;

                sb.AppendLine($"        cancellation.Entering(\"{mod}\");");

                if (handler.SkipOnRaiser)
                    sb.AppendLine("        if (!ctx.RaisedHere)");

                var indent = handler.SkipOnRaiser ? "            " : "        ";
                sb.AppendLine($"{indent}{Field(handler.Owner)}.{handler.Method.Name}({Arguments(handler)});");

                // A refusal stops the rest of this stage too, so the guard goes after each handler that can
                // refuse rather than once at the end of the stage.
                if (onServer && stage is Stage.Validate or Stage.Filter)
                {
                    sb.AppendLine("        if (cancellation.IsCancelled)");
                    sb.AppendLine("        {");
                    sb.AppendLine("            Refuse(in e, ctx, cancellation);");
                    sb.AppendLine("            return;");
                    sb.AppendLine("        }");
                }
            }

            sb.AppendLine();
        }

        if (onServer && scope != Scope.Server)
        {
            // A subject in no cell or area leaves the event with no audience. One bad event must not take the
            // server down, so the lookup is try-shaped and dispatch drops it.
            if (scope is Scope.Cell or Scope.Area)
            {
                var find = scope == Scope.Cell ? "TryCellOf" : "TryAreaOf";
                sb.AppendLine(
                    $"        if (!{ServerEvents}.ServerNetworkEventScopes.{find}(this, e.{subject!.Name}, out var audience))");
                sb.AppendLine("            return;");
                sb.AppendLine();
            }

            sb.AppendLine($"        {ServerEvents}.ServerNetworkEventTransport.FanOut("
                          + $"this, Code(), {Audience(scope, subject, target)}, origin, Written(in e));");
        }

        sb.AppendLine("    }");

        sb.AppendLine();

        if (onServer)
        {
            sb.AppendLine("    /// <summary>The server raising it for itself, or for a player it is acting on behalf of.</summary>");
            sb.AppendLine($"    public void Raise({type} e, global::ReadyM.Api.Idents.PlayerId origin, bool vouched)");
            sb.AppendLine("        => Dispatch(e, origin, true, vouched);");
            sb.AppendLine();
            sb.AppendLine("    /// <summary>Takes this event off the wire. The sender is the origin; the relay vouches for that.</summary>");
            sb.AppendLine("    protected override void Listen() => Hear(Code(), Arrived);");
            sb.AppendLine();
            sb.AppendLine("    private void Arrived("
                          + "global::ReadyM.Api.Multiplayer.Protocol.ServerEventHeader header, NetDataReader reader)");
            sb.AppendLine("    {");
            sb.AppendLine($"        if (!TryRead(reader, out {type} e))");
            sb.AppendLine("            return;");
            sb.AppendLine();
            sb.AppendLine("        Dispatch(e, header.Sender, false, false);");
            sb.AppendLine("    }");
        }
        else
        {
            sb.AppendLine("    /// <summary>A client sends a raised event to the server, the only place it goes. The");
            sb.AppendLine("    /// origin is whoever the relay says sent it, so the client does not name itself.</summary>");
            sb.AppendLine($"    public void Raise({type} e, global::ReadyM.Api.Idents.PlayerId origin, bool vouched)");
            sb.AppendLine($"        => {Events}.NetworkEventTransport.SendToServer(this, Code(), Written(in e));");
            sb.AppendLine();
            sb.AppendLine("    /// <summary>Takes this event, or a refusal of one this machine raised, off the wire.</summary>");
            sb.AppendLine("    protected override void Listen() => Hear(Code(), Arrived);");
            sb.AppendLine();
            EmitArrived(sb, type, reject, handlers);
        }

        if (onServer)
        {
            sb.AppendLine();
            sb.AppendLine($"    private void Refuse(in {type} e, {Events}.EventContext ctx, {Events}.EventCancellation cancellation)");
            sb.AppendLine("    {");
            sb.AppendLine($"        {ServerEvents}.ServerNetworkEventTransport.Reject(this, Code(), ctx.Origin, Refused(in e, cancellation));");
            EmitRejected(sb, handlers);
            sb.AppendLine("    }");
        }
        else
        {
            sb.AppendLine();
            sb.AppendLine($"    public void Refused(in {type} e, {Events}.EventContext ctx, {Events}.EventCancellation cancellation)");
            sb.AppendLine("    {");
            EmitRejected(sb, handlers);
            sb.AppendLine("    }");
        }

        sb.AppendLine();
        sb.AppendLine($"    private static NetDataWriter Written(in {type} e)");
        sb.AppendLine("    {");
        sb.AppendLine("        var writer = new NetDataWriter();");
        sb.AppendLine("        e.Serialize(writer);");
        sb.AppendLine("        return writer;");
        sb.AppendLine("    }");

        EmitRegistration(sb, declared, type, onServer);
        EmitRead(sb, declared, type);

        if (onServer)
            EmitRefused(sb, type, reject);
        sb.AppendLine("}");
        sb.AppendLine();
    }

    /// <summary>
    /// A client's half of the wire: the event, which runs the stages that reach a client, or a refusal of one
    /// this machine raised, which runs Rejected and nothing else. Both arrive on the event's own code.
    /// </summary>
    private static void EmitArrived(
        StringBuilder sb, string type, INamedTypeSymbol? reject, List<Handler> handlers)
    {
        var rejected = handlers.Where(h => h.Stage == Stage.Rejected).ToList();

        sb.AppendLine("    private void Arrived("
                      + "global::ReadyM.Api.Multiplayer.Protocol.ServerEventHeader header, NetDataReader reader)");
        sb.AppendLine("    {");
        sb.AppendLine($"        if (!{Events}.NetworkEventFrame.TryRead(reader, out var frame))");
        sb.AppendLine("            return;");
        sb.AppendLine();
        sb.AppendLine($"        if (!TryRead(reader, out {type} e))");
        sb.AppendLine("            return;");
        sb.AppendLine();
        sb.AppendLine("        if (frame.Refused)");
        sb.AppendLine("        {");
        sb.AppendLine("            GuessFailed();");
        sb.AppendLine();

        if (rejected.Count == 0)
        {
            sb.AppendLine("            return;");
        }
        else
        {
            sb.AppendLine($"            var cancellation = new {Events}.EventCancellation();");
            sb.AppendLine("            cancellation.Entering(reader.GetString());");
            sb.AppendLine($"            cancellation.Cancel({Reason(reject!)});");
            sb.AppendLine($"            var refusal = new {Events}.EventContext("
                          + "frame.Origin, frame.Origin == Me, cancellation);");
            sb.AppendLine();
            EmitRejected(sb, handlers, "            ", "refusal");
        }

        sb.AppendLine("            return;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        Dispatch(e, frame.Origin, frame.Origin == Me, true);");
        sb.AppendLine("    }");
    }

    /// <summary>
    /// The reason off the wire. Only reached where a Rejected handler exists, and NEVT012 stops one on an event
    /// that named no reject type, so there is always a type to read.
    /// </summary>
    private static string Reason(INamedTypeSymbol reject)
    {
        var named = reject.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var read = reject.TypeKind == TypeKind.Enum
            ? $"({named})reader.GetInt()"
            : $"reader.Get<{named}>()";

        return $"reader.GetByte() == 1 ? {read} : (object?)null";
    }

    /// <summary>
    /// Puts this dispatch in the container, which is also what starts it listening. A mod names its events and
    /// its handlers and nothing else, so this runs itself: the mod loader runs it for every assembly it loads,
    /// and a module initializer runs it where the target has one, so it has to be safe to say twice.
    /// </summary>
    private static void EmitRegistration(StringBuilder sb, INamedTypeSymbol declared, string type, bool onServer)
    {
        var side = onServer ? "Server" : "Client";

        sb.AppendLine();
        sb.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        sb.AppendLine("    internal static class Registration");
        sb.AppendLine("    {");
        sb.AppendLine("        private static bool _registered;");
        sb.AppendLine();
        sb.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("        public static void Register()");
        sb.AppendLine("        {");
        sb.AppendLine("            if (_registered)");
        sb.AppendLine("                return;");
        sb.AppendLine();
        sb.AppendLine("            _registered = true;");
        sb.AppendLine();
        sb.AppendLine($"            {Events}.NetworkEventRegistry.Declare<{declared.Name}Dispatch, {type}>(");
        sb.AppendLine($"                global::ReadyM.Api.Multiplayer.RPC.RpcSide.{side});");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    /// <summary>
    /// Reads an event back off the wire, in the order it wrote itself. Entity members name an id this end may
    /// not have, so a miss drops the whole event: half an event is worse than none, and the sender's own end
    /// has already been told whether it was accepted.
    /// </summary>
    private static void EmitRead(StringBuilder sb, INamedTypeSymbol declared, string type)
    {
        // Settable only: an event's own members all have a setter, and what the generator added to the struct
        // beside them, its code, does not. Reading that back would mean assigning it.
        var members = declared.GetMembers()
            .OfType<IPropertySymbol>()
            .Where(p => !p.IsStatic && p.SetMethod is not null)
            .ToList();

        sb.AppendLine();
        sb.AppendLine($"    private bool TryRead(NetDataReader reader, out {type} e)");
        sb.AppendLine("    {");
        sb.AppendLine("        e = default;");
        sb.AppendLine();

        for (var i = 0; i < members.Count; i++)
        {
            var member = members[i];

            if (RpcEntityParams.IsShape(member.Type, out var shape, out var optional))
            {
                var read = optional ? "TryReadOptional" : "TryRead";
                var named = shape.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

                sb.AppendLine(
                    $"        if (!{Events}.NetworkEventCodec.{read}<{named}>("
                    + $"this, reader, out var m{i}, \"{declared.Name}\", \"{member.Name}\"))");
                sb.AppendLine("            return false;");
            }
            else
            {
                sb.AppendLine($"        var m{i} = {Reader(member.Type)};");
            }
        }

        sb.AppendLine();
        sb.AppendLine($"        e = new {type}");
        sb.AppendLine("        {");

        for (var i = 0; i < members.Count; i++)
            sb.AppendLine($"            {members[i].Name} = m{i},");

        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine("        return true;");
        sb.AppendLine("    }");
    }

    /// <summary>How one plain member reads itself back, cast where the wire carries the underlying type.</summary>
    private static string Reader(ITypeSymbol type)
    {
        if (type.TypeKind == TypeKind.Enum)
        {
            var underlying = SerializationHelper.GetEnumBaseType(type);
            var named = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

            return $"({named})reader.{SerializationHelper.GetDeserializationMethod(underlying)}()";
        }

        if (SerializationHelper.IsINetSerializable(type))
        {
            var named = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

            return $"reader.Get<{named}>()";
        }

        return $"reader.{SerializationHelper.GetDeserializationMethod(type.SpecialType)}()";
    }

    /// <summary>
    /// What a refusal carries back to the origin: the event as it stood when it was refused, the mod that
    /// refused it, and the reason when the event declared a type for one. The reason gets a presence byte
    /// because an event may name a reject type and still be cancelled without one.
    /// </summary>
    private static void EmitRefused(StringBuilder sb, string type, INamedTypeSymbol? reject)
    {
        sb.AppendLine();
        sb.AppendLine($"    private static NetDataWriter Refused(in {type} e, {Events}.EventCancellation cancellation)");
        sb.AppendLine("    {");
        sb.AppendLine("        var writer = new NetDataWriter();");
        sb.AppendLine("        e.Serialize(writer);");
        sb.AppendLine("        writer.Put(cancellation.StoppedBy);");

        if (reject is not null)
        {
            var name = reject.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var value = reject.TypeKind == TypeKind.Enum ? "(int)reason" : "reason";

            sb.AppendLine($"        if (cancellation.Reason is {name} reason)");
            sb.AppendLine("        {");
            sb.AppendLine("            writer.Put((byte)1);");
            sb.AppendLine($"            writer.Put({value});");
            sb.AppendLine("        }");
            sb.AppendLine("        else");
            sb.AppendLine("        {");
            sb.AppendLine("            writer.Put((byte)0);");
            sb.AppendLine("        }");
        }

        sb.AppendLine();
        sb.AppendLine("        return writer;");
        sb.AppendLine("    }");
    }

    /// <summary>
    /// The Rejected handlers. An event with no reject type still refuses, so a handler that takes no reason is
    /// called all the same: dropping it would be a handler that silently never fires.
    /// </summary>
    private static void EmitRejected(
        StringBuilder sb, List<Handler> handlers, string indent = "        ", string ctx = "ctx")
    {
        foreach (var handler in handlers.Where(h => h.Stage == Stage.Rejected))
        {
            var call = $"{indent}{Field(handler.Owner)}.{handler.Method.Name}(in e";

            if (handler.Reason is { } reason)
                call += $", ({reason.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)})cancellation.Reason!";

            if (handler.TakesContext)
                call += $", {ctx}";

            sb.AppendLine(call + ");");
        }
    }

    private static string Audience(Scope scope, IPropertySymbol? subject, IPropertySymbol? target) => scope switch
    {
        Scope.Global => $"{Events}.EventAudience.Global",
        Scope.Single => $"{Events}.EventAudience.Single(e.{target!.Name}.PlayerId)",
        Scope.Area => $"{Events}.EventAudience.InArea(audience)",
        Scope.Cell => $"{Events}.EventAudience.InCell(audience)",
        _ => $"{Events}.EventAudience.Server",
    };

    private static string Arguments(Handler handler)
    {
        var self = handler.ByRef ? "ref e" : "in e";
        return handler.TakesContext ? $"{self}, ctx" : self;
    }

    private static string Field(ISymbol owner) => char.ToLowerInvariant(owner.Name[0]) + owner.Name.Substring(1);

    private static IPropertySymbol? Member(INamedTypeSymbol declared, string attribute)
        => declared.GetMembers().OfType<IPropertySymbol>()
            .FirstOrDefault(p => p.GetAttributes().Any(a => a.AttributeClass?.Name == attribute));

    private static void Report(
        SourceProductionContext context, Location? location, string id, string title, string message)
        => context.ReportDiagnostic(Diagnostic.Create(
            new DiagnosticDescriptor(id, title, message, "NetworkEvent", DiagnosticSeverity.Error, true),
            location));

    /// <summary>One <c>[EventHandler]</c> method, with what its attribute and its signature said.</summary>
    /// <summary>
    /// Dispatch takes its handlers as constructor parameters, so it can be no more accessible than the least
    /// accessible of them. A mod that keeps a handler class to itself, which is the normal thing to do since
    /// nothing outside the mod calls it, gets an internal dispatcher. Its own generated registration is in the
    /// same assembly, so that is all it needs.
    /// </summary>
    private static string Visibility(List<ISymbol?> owners)
        => owners.All(PubliclyVisible) ? "public" : "internal";

    /// <summary>Whether a type and everything it is nested in are public.</summary>
    private static bool PubliclyVisible(ISymbol? symbol)
    {
        for (var current = symbol; current is INamedTypeSymbol type; current = type.ContainingType)
            if (type.DeclaredAccessibility != Accessibility.Public)
                return false;

        return true;
    }

    private sealed class Handler
    {
        private Handler(INamedTypeSymbol owner, IMethodSymbol method) => (Owner, Method) = (owner, method);

        public INamedTypeSymbol Owner { get; }

        public IMethodSymbol Method { get; }

        public Stage Stage { get; private set; }

        public bool SkipOnRaiser { get; private set; }

        public string? After { get; private set; }

        public INamedTypeSymbol Event { get; private set; } = null!;

        public INamedTypeSymbol? Reject { get; private set; }

        public INamedTypeSymbol? Reason { get; private set; }

        public bool ByRef { get; private set; }

        public bool TakesContext { get; private set; }

        public static Handler? Read(INamedTypeSymbol owner, IMethodSymbol method)
        {
            var attribute = method.GetAttributes().First(a => a.AttributeClass?.Name == HandlerAttribute);

            if (method.Parameters.Length == 0 || method.Parameters[0].Type is not INamedTypeSymbol declared)
                return null;

            var declaration = declared.GetAttributes()
                .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == EventAttribute);

            if (declaration is null)
                return null;

            var stage = attribute.ConstructorArguments.Length > 0
                ? (Stage)System.Convert.ToInt32(attribute.ConstructorArguments[0].Value)
                : Stage.Observe;

            var reason = method.Parameters.Length > 1
                ? method.Parameters[1].Type as INamedTypeSymbol
                : null;

            return new Handler(owner, method)
            {
                Stage = stage,
                SkipOnRaiser = Named(attribute, "SkipOnRaiser") is true,
                After = Named(attribute, "After") as string,
                Event = declared,
                Reject = declaration.NamedArguments
                    .FirstOrDefault(n => n.Key == "Reject").Value.Value as INamedTypeSymbol,
                Reason = stage == Stage.Rejected ? reason : null,
                ByRef = method.Parameters[0].RefKind == RefKind.Ref,
                TakesContext = method.Parameters.Any(p => p.Type.Name == "EventContext"),
            };
        }

        private static object? Named(AttributeData attribute, string name)
            => attribute.NamedArguments.FirstOrDefault(n => n.Key == name).Value.Value;
    }

    /// <summary>Mirrors <c>ReadyM.SDK.Attributes.Stage</c>, which a generator cannot reference.</summary>
    private enum Stage
    {
        Validate,
        Filter,
        Apply,
        Observe,
        Rejected,
    }

    /// <summary>Mirrors <c>ReadyM.SDK.Attributes.Scope</c>. Read by name, so the order here is cosmetic.</summary>
    private enum Scope
    {
        Server,
