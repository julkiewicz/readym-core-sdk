using System;
using System.Linq;
using System.Text;
using ReadyM.Api.Generators.Derive.CSharp;
using ReadyM.Api.Generators.Derive.CSharp.Serialization;

namespace ReadyM.Api.Generators;

/// Emits <c>WriteSave</c>/<c>ReadSave</c> for a savable component or value.
/// <remarks>
/// Lifted out of <c>DeriveSavableComponentGenerator</c> so the archetype and mixin generators can reach it too, the
/// same way <c>ReplicatedComponentEmitter</c> was: generators cannot chain, so a component a shape declares has to
/// be finished by whoever emits it.
/// </remarks>
internal static class SaveComponentEmitter
{
    /// A component: <c>ISavableComponent</c>, with its save name and version baked in.
    internal static string Emit(DeriveTargetModel model, string saveName, ushort saveVersion)
        => Generate(model, (saveName, saveVersion));

    /// A value type: <c>ISaveSerializable</c>, written inside the component that holds it.
    internal static string EmitSerializable(DeriveTargetModel model)
        => Generate(model, null);

    private static string Generate(DeriveTargetModel model, (string Name, ushort Version)? component)
    {
        var info = model.Source;
        var isComponent = component is not null;
        var contract = isComponent ? "ISavableComponent" : "ISaveSerializable";

        var sb = new StringBuilder();
        var moduleState = new CSharpModuleState();
        var classState = new CSharpClassState(moduleState);
        moduleState.AddUsing("ReadyM.Api.Saves");
        moduleState.AddUsing("ReadyM.Api.Extensions");

        sb.Append($$"""
namespace {{info.Namespace}};

partial struct {{info.Name}} : {{contract}}
{

""");

        if (isComponent)
        {
            sb.AppendLine($$"""
    /// <exclude />
    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
    public readonly string SaveName => "{{component!.Value.Name}}";
    /// <exclude />
    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
    public readonly ushort SaveVersion => {{component!.Value.Version}};

""");
        }

        EmitWriteSave(sb, model, classState);
        EmitReadSave(sb, model, classState);

        sb.AppendLine("""
}
""");

        var usingSb = new StringBuilder();
        usingSb.Append("""
// <auto-generated/>
#nullable enable

""");

        foreach (var ns in moduleState.Usings.Distinct().OrderBy(static x => x, StringComparer.Ordinal))
        {
            usingSb.AppendLine($"using {ns};");
        }

        sb.Insert(0, usingSb.ToString());

        sb.AppendLine("""

#nullable disable
""");

        return sb.ToString();
    }

    private static void EmitWriteSave(StringBuilder sb, DeriveTargetModel model, CSharpClassState classState)
    {
        sb.AppendLine("""
    /// <exclude />
    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
    public void WriteSave(ISaveWriter writer, ISaveWriteContext context)
    {
        writer.BeginObject();
""");

        var methodState = new CSharpMethodState(classState);
        foreach (var member in model.Members)
        {
            if (!ShouldSerialize(member))
                continue;

            var context = new CSharpEmitSerializeContext(
                new CSharpEmitState(sb, methodState),
                CSharpFieldSupportRegistry.EmitSerializeVisitor,
                CSharpFieldSupportRegistry.SaveCodec);
            context.State.ResetIndent("        ");
            context.AppendLine($"writer.Name(\"{SaveKey(member.Source.Name)}\");");
            context.EmitSerializeVar(member.Source.Name, member.Source.Type);
        }

        sb.AppendLine("""
        writer.EndObject();
    }

""");
    }

    private static void EmitReadSave(StringBuilder sb, DeriveTargetModel model, CSharpClassState classState)
    {
        sb.AppendLine("""
    /// <exclude />
    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
    public void ReadSave(ISaveReader reader, ISaveLoadContext context)
    {
        reader.BeginObject();
""");

        var methodState = new CSharpMethodState(classState);
        foreach (var member in model.Members)
        {
            if (!ShouldSerialize(member))
                continue;

            var context = new CSharpEmitDeserializeContext(
                new CSharpEmitState(sb, methodState),
                CSharpFieldSupportRegistry.EmitDeserializeVisitor,
                CSharpFieldSupportRegistry.SaveCodec);
            context.State.ResetIndent("        ");

            context.AppendLine($"if (reader.TryName(\"{SaveKey(member.Source.Name)}\"))");
            using (context.WithCodeBlock())
            {
                context.EmitDeserializeVar(member.Source.Name, member.Source.Type);
            }
        }

        sb.AppendLine("""
        reader.EndObject();
    }
""");
    }

    private static bool ShouldSerialize(DeriveMemberModel member)
        => !IsIgnored(member);

    private static bool IsIgnored(DeriveMemberModel member)
        => AttributeUtils.HasAttribute(member.Source.Symbol, "SaveIgnoreAttribute");

    // The on-disk field key: strip a leading underscore and capitalise, so "_items" reads as "Items".
    private static string SaveKey(string fieldName)
        => fieldName.Length > 1 && fieldName[0] == '_'
            ? char.ToUpperInvariant(fieldName[1]) + fieldName.Substring(2)
            : fieldName;
}
